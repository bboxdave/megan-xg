"""
Stage 3 of the effect-conversion pipeline. Reads data/effect_conv.json (from
map_effect_conv.py) + data/tables.json and emits codec/MU100EffectConv.h: a
JUCE-free data header carrying

  - the 11 raw->display conversion tables the PDF prints, plus any DERIVED_TABLES
    defined below (tables the PDF gives only as a range)
  - per layout id (MU100Effects.h kLayouts), a 16-slot conversion descriptor
    {rawMin, rawMax, kind, table, dispMin, dispMax, decimals, signedShow, unit,
     enums}

The plugin's Source/XgEffectFormat.h consumes this to set each Effect-Parameters
knob's range + value formatter (Hz/dB/ms/%/signed/enum/pan) instead of raw
0-127. The plugin compiles the generated header directly; rebuild after running.

Run:  python tools/gen_effect_conv.py
"""
import json
from spdx_header import CPP_LINES
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONV = ROOT / "data" / "effect_conv.json"
TABLES = ROOT / "data" / "tables.json"
OUT = ROOT / "codec" / "MU100EffectConv.h"

KIND = {"none": "CK_NONE", "plain": "CK_PLAIN", "table": "CK_TABLE",
        "linear": "CK_LINEAR", "enum": "CK_ENUM", "pan": "CK_PAN",
        "special": "CK_SPECIAL"}


# --------------------------------------------------------------- derived tables
# tables.json mirrors the Sound List PDF's eleven "Effect Data Assign" tables and
# is regenerated by extract_tables.py, so a table the PDF does NOT print has to be
# built here instead.
#
# table#12, LO-FI sampling frequency: the PDF gives this control only as a RANGE,
# "44.1kHz - 345Hz" over raw 0-127, and its two endpoints are quoted in DIFFERENT
# units, so the range parser turned it into a linear ramp 44.1 -> 345 with no unit
# -- ascending, when the real quantity descends. The law is the decimator's
# divider, 44100/(raw+1) Hz: raw 0 -> 44100, raw 127 -> 44100/128 = 344.5, i.e.
# exactly the two endpoints the PDF quotes. Confirmed on the emulated SWP30, whose
# LO-FI sample-and-hold was measured firing at 44100/(raw+1) Hz (raw 0 -> 44100/s,
# raw 2 -> 14700/s, raw 7 -> 5513/s, raw 127 -> 344.5/s).
def _lofi_sampling_freq():
    def fmt(v):
        hz = 44100.0 / (v + 1)
        return ("%.1fk" % (hz / 1000.0)) if hz >= 1000 else ("%.0f" % hz)
    return [fmt(v) for v in range(128)]


DERIVED_TABLES = {
    "table#12": {"name": "Lo-Fi Sampling Frequency", "min": 0, "max": 127,
                 "count": 128, "values": _lofi_sampling_freq()},
}


def cstr(s):
    if s is None:
        return "nullptr"
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{s}"'


def cflt(x):
    """A valid C++ float literal (always has a decimal point + 'f' suffix)."""
    g = "%g" % float(x)
    if "." not in g and "e" not in g and "E" not in g:
        g += ".0"
    return g + "f"


def main():
    conv = json.load(open(CONV, encoding="utf-8"))["layouts"]
    tables = dict(json.load(open(TABLES, encoding="utf-8"))["tables"])
    tables.update(DERIVED_TABLES)

    out = []
    w = out.append
    out.extend(CPP_LINES)
    w("// MU100EffectConv.h — generated by tools/gen_effect_conv.py from")
    w("// data/effect_conv.json (map_effect_conv.py) + data/tables.json, plus the")
    w("// derived tables in gen_effect_conv.py (DERIVED_TABLES).")
    w("// Per-layout effect-parameter value conversions (raw range + unit/table)")
    w("// so the Effect-Parameters knobs read in real units like XGEdit.")
    w("// DO NOT EDIT BY HAND. Regenerate, then rebuild the plugin.")
    w("#pragma once")
    w("#include <cstdint>")
    w("")
    w("namespace mu100fx {")
    w("")
    w("enum ConvKind : uint8_t {")
    w("  CK_NONE = 0, CK_PLAIN, CK_TABLE, CK_LINEAR, CK_ENUM, CK_PAN, CK_SPECIAL")
    w("};")
    w("")
    w("// A raw->display conversion table (value strings indexed by the raw value).")
    w("struct ConvTable { const char* name; uint16_t count; const char* const* values; };")
    w("")
    w("// Per-knob-slot conversion descriptor.")
    w("//  kind==CK_TABLE  : display = table[clamp(raw,0,count-1)]")
    w("//  kind==CK_LINEAR : display = dispMin + (raw-rawMin)*(dispMax-dispMin)/(rawMax-rawMin)")
    w("//                    formatted to 'decimals' places + 'unit'; '+' shown if signedShow")
    w("//  kind==CK_ENUM   : display = enums split on '|', indexed (raw-rawMin)")
    w("//  kind==CK_PAN    : raw 1..127 -> L63..C..R63")
    w("//  kind==CK_PLAIN / CK_SPECIAL / CK_NONE : raw integer")
    w("struct SlotConv {")
    w("  int16_t  rawMin, rawMax;")
    w("  uint8_t  kind;        // ConvKind")
    w("  uint8_t  table;       // 1..12 when kind==CK_TABLE, else 0")
    w("  float    dispMin, dispMax;")
    w("  uint8_t  decimals;")
    w("  uint8_t  signedShow;  // show leading '+' for positive linear values")
    w("  uint8_t  varOnly;     // 1 = valid only in the Variation block (hide in")
    w("                        //     the Chorus/Insertion block); e.g. chorus mid-EQ")
    w("  const char* unit;     // linear unit suffix (\"\", \"ms\", \"dB\", \"s\", \"m\", \"%\")")
    w("  const char* enums;    // '|'-joined option list for CK_ENUM, else nullptr")
    w("  // Block-dependent range: when altRawMax > altRawMin, these REPLACE")
    w("  // rawMin/rawMax (and dispMin/dispMax) outside the Variation block.")
    w("  // Only PHASER1's STAGE uses it -- 4..12 as a Variation, 4..6 in the")
    w("  // Chorus/Insertion blocks, per the spec table and confirmed against")
    w("  // the device. Ask xgfmt::rangeFor(), never rawMin/rawMax directly.")
    w("  int16_t  altRawMin, altRawMax;")
    w("  float    altDispMin, altDispMax;")
    w("};")
    w("struct LayoutConv { SlotConv slots[16]; };")
    w("")

    # ---- conversion tables ----
    maxn = max(int(k.split("#")[1]) for k in tables)
    table_arrays = {}
    for k, t in tables.items():
        n = int(k.split("#")[1])
        arr = f"kConvTable{n}_vals"
        table_arrays[n] = (arr, t["name"], t["values"])
    for n in sorted(table_arrays):
        arr, name, vals = table_arrays[n]
        w(f"static const char* const {arr}[] = {{")
        line = "  "
        for v in vals:
            tok = cstr(v) + ", "
            if len(line) + len(tok) > 96:
                w(line.rstrip())
                line = "  "
            line += tok
        w(line.rstrip())
        w("};")
    w("")
    w(f"static const ConvTable kConvTables[{maxn + 1}] = {{")
    w("  { nullptr, 0, nullptr }, // [0] unused (tables are 1-based)")
    for n in range(1, maxn + 1):
        if n in table_arrays:
            arr, name, vals = table_arrays[n]
            w(f"  {{ {cstr(name)}, {len(vals)}, {arr} }}, // table#{n}")
        else:
            w(f"  {{ nullptr, 0, nullptr }}, // table#{n} (missing)")
    w("};")
    w(f"static const int kConvTableCount = {maxn};")
    w("")

    # ---- per-layout slot conversions ----
    max_lid = max(int(k) for k in conv)
    w(f"// Indexed by layout id (kLayouts in MU100Effects.h). [0] = NO EFFECT.")
    w(f"static const LayoutConv kLayoutConv[{max_lid + 1}] = {{")
    for lid in range(max_lid + 1):
        slots = conv.get(str(lid))
        if slots is None:
            # layout 0 or any unmapped -> all CK_NONE
            empty = "{0,0,CK_NONE,0,0.0f,0.0f,0,0,0,nullptr,nullptr,0,0,0.0f,0.0f}"
            w("  {{ " + ", ".join([empty] * 16) + f" }}}}, // {lid}")
            continue
        cells = []
        for c in slots:
            k = KIND[c["kind"]]
            rmin = c.get("rawMin", 0)
            rmax = c.get("rawMax", 0)
            tab = c.get("table", 0) if c["kind"] == "table" else 0
            dmin = c.get("dispMin", 0.0)
            dmax = c.get("dispMax", 0.0)
            dec = c.get("decimals", 0)
            sgn = 1 if c.get("signed") else 0
            vonly = 1 if c.get("varBlockOnly") else 0
            unit = cstr(c.get("unit", "")) if c["kind"] == "linear" else "nullptr"
            if c["kind"] == "enum":
                enums = cstr("|".join(c["enums"]))
            elif c["kind"] == "special" and c.get("special"):
                # boundary letters for the balance display, e.g. "D|W" / "E|R"
                enums = cstr("|".join(c["special"]))
            else:
                enums = "nullptr"
            armin = c.get("altRawMin", 0)
            armax = c.get("altRawMax", 0)
            admin = c.get("altDispMin", 0.0)
            admax = c.get("altDispMax", 0.0)
            cells.append(
                f"{{{rmin},{rmax},{k},{tab},{cflt(dmin)},{cflt(dmax)},{dec},{sgn},{vonly},{unit},{enums},"
                f"{armin},{armax},{cflt(admin)},{cflt(admax)}}}")
        w(f"  {{ {{ " + ", ".join(cells) + f" }} }}, // {lid}")
    w("};")
    w(f"static const int kLayoutConvCount = {max_lid + 1};")
    w("")
    w("} // namespace mu100fx")
    w("")

    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}", file=sys.stderr)
    print(f"  layouts: {max_lid}, tables: {maxn}", file=sys.stderr)


if __name__ == "__main__":
    main()
