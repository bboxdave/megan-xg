"""
Extract the MU100 MIDI Parameter Change tables (the device address map) from
MU100_sound_list_midi_data.pdf into data/parameters.json.

This is the "spine" of the editor: every editable parameter (System, Multi EQ,
Effect 1/2, Multi Part, A/D Part, Drum Setup, MU-native ...) has an entry giving
its SysEx Address (High/Mid/Low), data Size, raw value Range, name, description
and factory default.

WHY THIS READS THE PDF DIRECTLY (and not reference/sound_list.txt)
-----------------------------------------------------------------
The first version of this tool parsed `pdftotext -layout` output. That output
interleaves the page's columns into single lines, and where a Description cell
wraps onto extra lines the Parameter-name column drifts out of step with the
Address column. The result was a whole region of EFFECT 1 / EFFECT 2 carrying
the WRONG name for its address (and stray Default-value tokens like "40" / "7F"
promoted to parameter names) — see git history for the damage.

The PDF itself is not ambiguous: every table row is one horizontal band, and the
columns sit at fixed x offsets from the table's left edge. So we read positioned
words (PyMuPDF), group them into rows by y, and slice each row into columns by x.
Nothing has to be inferred from column ORDER, which is what used to drift.

Column geometry is expressed as offsets from `L`, the table's left edge, because
the page margin alternates (recto/verso) by ~6pt. `L` is measured per page from
the range column's lone "-" separators, which are abundant and unambiguous.

Run:  python tools/extract_parameters.py
"""
import itertools
import json
import re
import statistics
import sys
from pathlib import Path

import fitz  # PyMuPDF

ROOT = Path(__file__).resolve().parent.parent
PDF = ROOT / "reference" / "MU100_sound_list_midi_data.pdf"
OUT = ROOT / "data" / "parameters.json"

SECTION_END_MARKER = "XG Voice List"

# Column boundaries as offsets from the table's left edge L. A word belongs to
# the last column whose start offset it is >=. Measured from the PDF (the same
# numbers hold on both margins once L is subtracted).
#
# The boundaries sit in MEASURED gaps, not guesses: across the whole section the
# name column occupies offsets 127..232, description 241..315 and default 334+,
# so 236 and 325 fall in empty space. Do not narrow them by "a couple of points
# of slack" — 236 already has only 4pt of clearance, and a name ending in a
# short word (…PARAMETER10 LSB, offset 229) lands right against it.
COLUMNS = [
    (0,   "addr_h"),
    (14,  "addr_m"),
    (31,  "addr_l"),
    (50,  "size"),
    (75,  "range"),
    (118, "name"),
    (236, "desc"),
    (325, "default"),
]

DASH_OFFSET = 92        # x offset of the range column's "-" separator from L
ROW_TOL = 5             # pt; words within this of a row's first word join it

# Facts the manual does not state, applied on top of the extraction. Keyed by
# (table, high, mid, low) — an address, not a name, so a wording change in the
# manual can't silently detach an override from its parameter.
#
# These MUST live here rather than as hand-edits to parameters.json: that file
# is fully regenerated by this tool, so anything edited into it is destroyed on
# the next run. (DETUNE's encoding was exactly such a hand-edit, and the codec
# test caught its loss.)
OVERRIDES = {
    # Size 2, but XG big-endian nibble packing, NOT an independent 7-bit byte
    # pair like the effect TYPE/PARAMETER fields. Verified by the codec test
    # against the factory dump (combined 0x80, encodes to 08 00).
    ("MULTI PART", "08", "nn", "09"): {"enc": "NIBBLE"},
}

HEADER_RE = re.compile(r"MIDI Parameter Change table\s*\(([^)]+)\)")
TOTAL_SIZE_RE = re.compile(r"^TOTAL SIZE", re.I)
COLHDR_RE = re.compile(r"^Address\b|^\(H\)|^Size\b")
TABLE_NUM_RE = re.compile(r"^<\s*Table\b")
RUNNING_HEAD_RE = re.compile(r"^MIDI data format$|^\d+$"
                             r"|^\d+\s+MU100 MIDI$|^MU100 MIDI\s+\d+$")

# Address byte: hex pair, or a documented placeholder nibble/byte.
BYTE_RE = re.compile(r"^(?:[0-9A-F]{2}|nn|pp|tt|mm|rr|[0-9][n])$")
HEX2_RE = re.compile(r"^[0-9A-F]{2}$")
DITTO = "˝"        # the doc's "same as above" mark


def page_rows(page):
    """[(y, [words])] for one page; words sorted left-to-right within a row."""
    words = list(page.get_text("words"))
    words.sort(key=lambda w: (w[1], w[0]))
    rows, cur, cur_y = [], [], None
    for w in words:
        if cur_y is None or w[1] - cur_y <= ROW_TOL:
            if cur_y is None:
                cur_y = w[1]
            cur.append(w)
        else:
            rows.append((cur_y, sorted(cur, key=lambda x: x[0])))
            cur, cur_y = [w], w[1]
    if cur:
        rows.append((cur_y, sorted(cur, key=lambda x: x[0])))
    return rows


def left_edge(rows):
    """Measure the table's left edge from the range column's "-" separators.

    Only hyphens flanked by 2-hex-digit tokens count, which excludes the
    "< Table 1 - 4 >" captions (flanked by single digits).
    """
    xs = []
    for _, ws in rows:
        for i, w in enumerate(ws):
            if w[4] != "-" or i == 0 or i + 1 >= len(ws):
                continue
            if HEX2_RE.match(ws[i - 1][4]) and HEX2_RE.match(ws[i + 1][4]):
                xs.append(w[0])
    return statistics.median(xs) - DASH_OFFSET if xs else None


def split_columns(words, L):
    """Bucket a row's words into the named columns by x offset from L."""
    cols = {name: [] for _, name in COLUMNS}
    for w in words:
        off = w[0] - L
        name = COLUMNS[0][1]
        for start, cname in COLUMNS:
            if off >= start:
                name = cname
        cols[name].append(w[4])
    return {k: " ".join(v).strip() for k, v in cols.items()}


def parse_size(tok):
    """Size column is hex ('1','2','4', and 'E' = 14 for Model Name)."""
    try:
        return int(tok, 16)
    except ValueError:
        return None


def parse_range(text):
    m = re.match(r"^([0-9A-F]{2})\s*-\s*([0-9A-F]{2})", text)
    return {"lo": m.group(1), "hi": m.group(2)} if m else None


def strip_half(name):
    """('REVERB TYPE MSB','MSB') -> 'REVERB TYPE'; else (name, None)."""
    m = re.match(r"^(.*?)\s+(MSB|LSB)$", name)
    return (m.group(1), m.group(2)) if m else (name, None)


def collect(doc):
    """Walk the parameter-table section, yielding (table_name, [param rows])."""
    tables, cur = [], None
    anomalies, size_fixes = [], []

    started = False
    for pno in range(doc.page_count):
        page = doc[pno]
        rows = page_rows(page)
        joined = [(y, ws, " ".join(w[4] for w in ws)) for y, ws in rows]

        if any(SECTION_END_MARKER in t for _, _, t in joined) and started:
            break
        if not started and not any(HEADER_RE.search(t) for _, _, t in joined):
            continue

        L = left_edge(rows)
        for y, ws, text in joined:
            h = HEADER_RE.search(text)
            if h:
                started = True
                cur = {"table": h.group(1).strip(), "params": []}
                tables.append(cur)
                continue
            if cur is None or L is None:
                continue
            if (TOTAL_SIZE_RE.match(text) or COLHDR_RE.match(text)
                    or TABLE_NUM_RE.match(text) or RUNNING_HEAD_RE.match(text)):
                continue

            c = split_columns(ws, L)
            # In the native performance tables the "same as above" mark is set
            # tight against the parameter name and lands in the name column.
            name = c["name"].replace(DITTO, " ").strip()
            name = re.sub(r"\s{2,}", " ", name)
            # The doc marks "same as the row above" with a double-acute; carrying
            # the literal glyph into the data would be noise.
            desc = "" if c["desc"].strip() == DITTO else c["desc"]
            dflt = c["default"]

            low = c["addr_l"] if BYTE_RE.match(c["addr_l"]) else None
            mid = c["addr_m"] if BYTE_RE.match(c["addr_m"]) else None
            high = c["addr_h"] if BYTE_RE.match(c["addr_h"]) else None
            size = parse_size(c["size"])
            rng = parse_range(c["range"])

            prev = cur["params"][-1] if cur["params"] else None

            def absorb(p, extra_desc=desc, extra_dflt=dflt):
                if extra_desc:
                    p["display_raw"] = (p["display_raw"] + " " + extra_desc).strip()
                if extra_dflt:
                    p["default_raw"] = (p["default_raw"] + " " + extra_dflt).strip()

            if not name and low is None:
                # Description/default overflow from the row above.
                if prev is not None and (desc or dflt):
                    absorb(prev)
                continue

            if name == ":" or name.startswith(": "):
                continue                      # the doc's vertical ellipsis rows

            # Every real table row carries a Data range or a Size. A row with
            # neither and no name is a caption that happens to sit over the
            # address columns — "Model ID = 59" would otherwise be read as a
            # nameless parameter at low byte 0x59.
            if not name and not c["size"] and not c["range"]:
                continue

            # A row carrying ONLY a name is the second line of a WRAPPED name
            # (e.g. MULTI PART 08 nn 06 is "SAME NOTE NUMBER KEY ON ASSIGN",
            # printed over two lines). Prose footnotes can't be confused with
            # this: they start at the address column, so they land in addr_h.
            if (name and low is None and mid is None and high is None
                    and not c["size"] and not c["range"]
                    and not desc and not dflt and prev is not None):
                prev["name"] = (prev["name"] + " " + name).strip()
                prev["_stem"] = prev["name"]
                continue

            base, half = strip_half(name)

            # The LSB line of a 2-byte parameter: same name stem, no address of
            # its own. It is the SECOND BYTE of the parameter above, not a new
            # one — treating it as new is exactly what used to shift the whole
            # block's addresses.
            #
            # The size is NOT part of the test: the manual prints size 1 for
            # INSERTION EFFECT2 PARAMETER10 (03 01 42) even though it has both
            # an MSB and an LSB row, and its 0x30..0x43 region is 10 params x 2
            # bytes. Having two half-rows is the stronger evidence, so trust it
            # and correct the size.
            # The native performance tables print the LSB row WITH its own
            # address (the byte after the MSB's) rather than leaving it blank.
            # Same parameter either way — merge whenever the stem matches and
            # the address lands inside the parameter above.
            same_stem = prev is not None and prev.get("_stem") == base
            in_prev_span = (
                same_stem and low is not None and prev["addr"]["low"]
                and HEX2_RE.match(low) and HEX2_RE.match(prev["addr"]["low"])
                and int(prev["addr"]["low"], 16) < int(low, 16)
                    <= int(prev["addr"]["low"], 16) + prev["size"] - 1)

            if half == "LSB" and same_stem and (low is None or in_prev_span):
                absorb(prev)
                if prev["size"] < 2:
                    prev["size"] = 2
                    size_fixes.append(f"{cur['table']} {base}: size 1 -> 2 (has MSB+LSB rows)")
                # Only NOW is the "MSB" suffix on the parent meaningless: the
                # entry covers both bytes. Where no LSB row merges in, MSB/LSB
                # are two independent 1-byte parameters (MULTI PART BANK SELECT
                # MSB / LSB) and the suffix is part of the name — the plugin
                # looks those up by their full name.
                prev["name"] = base
                continue

            if low is None:
                anomalies.append(f"p{pno} y{y:.0f} [{cur['table']}] no address: {text[:70]}")
                continue

            # A row with an address but no name, falling inside the byte span of
            # the parameter above, is one of that parameter's extra bytes (the
            # nibble-packed ones: MASTER TUNE, DETUNE, and the perf equivalents
            # spell out "1st bit3-0 -> bit7-4" per byte). Not a parameter.
            #
            # `>=` on the low bound, not `>`: the manual prints the DETUNE
            # continuation byte of MU80/MU50 INTERNAL PERFORMANCE with its
            # PARENT's address (3n pp 11 twice) instead of 12. Two parameters
            # never share an address, so a repeat can only be a continuation.
            if (not name and prev is not None and not prev["_half"]
                    and prev["addr"]["low"] and HEX2_RE.match(prev["addr"]["low"])
                    and HEX2_RE.match(low)
                    and int(prev["addr"]["low"], 16) <= int(low, 16)
                       < int(prev["addr"]["low"], 16) + prev["size"]):
                absorb(prev)
                continue

            cur["params"].append({
                "name": name,
                "_stem": base,
                "_half": half,
                "addr": {"high": high, "mid": mid, "low": low},
                "size": size if size else 1,
                "range": rng or {"lo": "00", "hi": "7F"},
                "display_raw": desc,
                "default_raw": dflt,
            })
    return tables, anomalies, size_fixes


def carry_addresses(tables):
    """Fill in high/mid bytes that the doc prints only on a block's first row."""
    for t in tables:
        hi = mid = None
        for p in t["params"]:
            a = p["addr"]
            if a["high"]:
                hi = a["high"]
                mid = None            # a new high byte restarts the block
            if a["mid"]:
                mid = a["mid"]
            a["high"], a["mid"] = hi, mid


def finalize(tables):
    """Normalise default_raw, drop scratch fields, flag anything still unclear."""
    for t in tables:
        for p in t["params"]:
            p.pop("_stem", None)
            p.pop("_half", None)
            # Default column carries "40" or "01 (= HALL1)" or "05 (˝)"; keep the
            # bytes, drop the gloss (which duplicates the description).
            #
            # Some defaults are CONDITIONAL and printed as prose instead
            # ("part10,26 = 7F other parts = 0", "Part10 = 2, Part26 = 4").
            # Harvesting hex out of those yields the PART NUMBERS, not a default
            # — so accept the cell only when every token left after removing the
            # parenthetical gloss is a hex byte. backfill_defaults.py fills the
            # rest from a real factory dump, which is authoritative anyway.
            d = re.sub(r"\([^)]*\)", " ", p["default_raw"] or "").split()
            p["default_raw"] = (" ".join(d)
                                if d and all(HEX2_RE.match(x) for x in d) else None)
            p["display_raw"] = re.sub(r"\s+", " ", p["display_raw"] or "").strip()
            p["review"] = (not p["name"]) or (not p["name"][:1].isalpha())
            a = p["addr"]
            p.update(OVERRIDES.get((t["table"], a["high"], a["mid"], a["low"]), {}))
        t["param_count"] = len(t["params"])


def main():
    if not PDF.exists():
        sys.exit(f"missing {PDF}")
    doc = fitz.open(str(PDF))
    tables, anomalies, size_fixes = collect(doc)
    carry_addresses(tables)
    finalize(tables)

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps({"tables": tables}, indent=2), encoding="utf-8")

    print(f"wrote {OUT}", file=sys.stderr)
    print(f"{'TABLE':<40} {'rows':>5} {'review':>7}", file=sys.stderr)
    tot = rev = 0
    for t in tables:
        r = sum(1 for p in t["params"] if p["review"])
        tot += t["param_count"]
        rev += r
        print(f"{t['table']:<40} {t['param_count']:>5} {r:>7}", file=sys.stderr)
    print(f"{'TOTAL':<40} {tot:>5} {rev:>7}  "
          f"({100 * rev // tot if tot else 0}% need review)", file=sys.stderr)
    if size_fixes:
        print("\nsize corrections (manual disagrees with itself):", file=sys.stderr)
        for s in size_fixes:
            print("  " + s, file=sys.stderr)
    if anomalies:
        print(f"\n{len(anomalies)} unplaced rows:", file=sys.stderr)
        for a in anomalies[:40]:
            print("  " + a, file=sys.stderr)


if __name__ == "__main__":
    main()
