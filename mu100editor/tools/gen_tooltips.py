"""gen_tooltips.py — generate codec/MU100Tooltips.h from data/tooltips.csv.

data/tooltips.csv is the human-editable source of truth (edit the `tooltip`
column; blank = no tooltip). This emits a header-only, JUCE-free lookup the
plugin compiles directly, like the other codec headers.

Run from the mu100editor root:  python tools/gen_tooltips.py, then rebuild.
"""
import csv, os
from spdx_header import CPP_LINES

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV = os.path.join(ROOT, "data", "tooltips.csv")
OUT = os.path.join(ROOT, "codec", "MU100Tooltips.h")

def cesc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

def main():
    rows = []
    with open(CSV, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            key = (r["key"] or "").strip()
            tip = (r["tooltip"] or "").strip()
            if key and tip:                      # blank tooltip => no entry (lookup returns "")
                rows.append((key, tip))
    rows.sort()

    L = []
    L.extend(CPP_LINES)
    L.append("// MU100Tooltips.h — generated by tools/gen_tooltips.py from data/tooltips.csv.")
    L.append("// Editor control hover text, mostly mined from XGEdit95.exe. DO NOT EDIT BY HAND;")
    L.append("// edit data/tooltips.csv, regenerate, then rebuild the plugin.")
    L.append("#pragma once")
    L.append("#include <string>")
    L.append("#include <unordered_map>")
    L.append("")
    L.append("namespace mu100 { namespace tooltips {")
    L.append("")
    L.append("// Look up a control's tooltip by its stable key (see build_tooltips.py for the")
    L.append('// key convention). Returns "" when there is no tooltip for the key.')
    L.append("inline const std::string& forKey(const std::string& key)")
    L.append("{")
    L.append("    static const std::unordered_map<std::string, std::string> m = {")
    for key, tip in rows:
        L.append(f'        {{ "{cesc(key)}", "{cesc(tip)}" }},')
    L.append("    };")
    L.append("    static const std::string none;")
    L.append("    auto it = m.find(key);")
    L.append("    return it == m.end() ? none : it->second;")
    L.append("}")
    L.append("")
    L.append("// Convenience keys for the common cases.")
    L.append("inline const std::string& forParam(const std::string& table, const std::string& param)")
    L.append('    { return forKey(table + \"|\" + param); }')
    L.append("inline const std::string& forEffect(const std::string& abbr)")
    L.append('    { return forKey(std::string(\"FX|\") + abbr); }')
    L.append("")
    L.append("// Effect slot tooltip with context disambiguation, most specific first:")
    L.append('//   FX|<effectName>|<abbr>   (per-program override, e.g. COMP+DIST+DLY|DELAY)')
    L.append('//   FX|<abbr>@<disp>         (by display-type id, e.g. R.DEL@2 vs R.DEL@6)')
    L.append('//   FX|<abbr>                (generic)')
    L.append("inline const std::string& forEffectSlot(const std::string& effectName,")
    L.append("                                        const std::string& abbr, int disp)")
    L.append("{")
    L.append('    const std::string& a = forKey(\"FX|\" + effectName + \"|\" + abbr);')
    L.append("    if (! a.empty()) return a;")
    L.append('    const std::string& b = forKey(\"FX|\" + abbr + \"@\" + std::to_string(disp));')
    L.append("    if (! b.empty()) return b;")
    L.append('    return forKey(\"FX|\" + abbr);')
    L.append("}")
    L.append("")
    L.append("}} // namespace mu100::tooltips")
    L.append("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print(f"wrote {OUT}  ({len(rows)} entries)")

if __name__ == "__main__":
    main()
