"""Bake data/voices.json into a JUCE-free C++ header (codec/MU100Voices.h).

voices.json (built by build_voices.py from XGVoice.ini) holds every selectable
voice/kit with full display names, the 8-character LCD name beside each, bank
MSB/LSB, program, model (XG/MU80/MU90/MU100 addition) and element count --
everything the Voice browser/list needs.
Kits (bank MSB 126/127) live in the same table; the browser groups all five
Column-1 categories by MSB. Rerun after editing voices.json.
"""
import json
from spdx_header import CPP_LINES
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MODEL_IX = {"XG": 0, "MU80": 1, "MU90": 2, "MU100": 3}


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    data = json.load(open(os.path.join(ROOT, 'data', 'voices.json'), encoding='utf-8'))
    voices = data['voices']

    # Category list = the Melody (bank MSB 0) instrument families, first-seen
    # order. Non-melodic voices (SFX/Exclusive/kits) are grouped by MSB, not
    # category, so their category index is unused (0).
    cats = []
    for v in voices:
        if v['msb'] == 0:
            c = v.get('category') or ''
            if c not in cats:
                cats.append(c)
    cat_ix = {c: i for i, c in enumerate(cats)}

    out = []
    w = out.append
    out.extend(CPP_LINES)
    w('// AUTO-GENERATED by tools/gen_voices.py - do not edit by hand.')
    w('// Source: data/voices.json (built from XGVoice.ini + data/short_names.json).')
    w('// Regenerate after edits.')
    w('#pragma once')
    w('#include <cstdint>')
    w('namespace mu100 {')
    w('')
    w('// model: 0=XG Standard 1=MU80 2=MU90 3=MU100 addition.  elements: 1 or 2.')
    w('struct VoiceEntry {')
    w('    uint8_t     pgm;       // 1..128 (MIDI program = pgm-1)')
    w('    uint8_t     msb, lsb;  // Bank Select MSB / LSB')
    w('    uint8_t     category;  // index into kVoiceCategories (melody only)')
    w('    uint8_t     model;     // 0=XG 1=MU80 2=MU90 3=MU100')
    w('    uint8_t     elements;  // 1 or 2')
    w('    bool        native;    // MSB0 LSB126/127')
    w('    const char* name;      // full display name')
    w('    const char* short8;    // 8-character LCD name, as the hardware shows it')
    w('};')
    w('')
    w('static const char* const kVoiceCategories[] = {')
    w('    ' + ', '.join(cstr(c) for c in cats))
    w('};')
    w('static const int kVoiceCategoryCount = %d;' % len(cats))
    w('')
    w('static const VoiceEntry kVoices[] = {')
    for v in voices:
        w('    {%d,%d,%d,%d,%d,%d,%s,%s,%s},' % (
            v['pgm'], v['msb'], v['lsb'],
            cat_ix.get(v.get('category'), 0) if v['msb'] == 0 else 0,
            MODEL_IX.get(v.get('model', 'XG'), 0), v.get('elements', 1),
            'true' if v.get('native') else 'false', cstr(v['name']),
            cstr(v['short'])))
    w('};')
    w('static const int kVoiceCount = %d;' % len(voices))
    w('')
    w('} // namespace mu100')
    w('')

    dest = os.path.join(ROOT, 'codec', 'MU100Voices.h')
    open(dest, 'w', encoding='utf-8').write('\n'.join(out))
    print('emitted %d voices, %d melody categories -> %s' % (len(voices), len(cats), dest))


if __name__ == '__main__':
    main()
