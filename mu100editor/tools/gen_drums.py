"""Bake data/drums.json into codec/MU100Drums.h (JUCE-free).

The XG Drum Map stores variation kits as DIFFERENCES from a base kit, but a
blank cell does NOT automatically mean "inherit": the PDF shades blanks two
ways, "Same as Standard Kit" and "No sound", and extract_drums.py reads that
shading into each kit's "inherits" list. Only those notes are merged from the
base kit; every other blank note is silent (nullptr). Resolving it here means
the plugin just looks up (kit, note) -> drum-voice name with no merge logic.

Base:   MSB 127 (Drum Kit) -> Standard Kit (127/0/1)
        MSB 126 (SFX Kit)  -> NONE. The SFX / Techno / Sakura / Small Latin kits
        are peers, not variations of SFX Kit 1: every blank on their drum-map
        page is shaded "No sound", and their "inherits" lists are empty.
        Treating SFX Kit 1 as their base (as this script did until 2026-08-25)
        invented drum-voice names for keys the device leaves silent -- e.g. SFX
        Kit 2 showed Insects / Bacteria / Haunted / Ghost / Maou, and Techno Kit
        K/S showed a whole block above A3 plus E0 / F0, none of which sound.

Run from mu100editor/ ; codec/MU100Drums.h is compiled by the plugin directly.
"""
import json
from spdx_header import CPP_LINES
import os

FIRST_NOTE = 13   # 0x0D
LAST_NOTE  = 91   # 0x5B

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    with open(os.path.join(HERE, 'data', 'drums.json'), encoding='utf-8') as f:
        data = json.load(f)
    kits = data['kits']

    def find(msb, lsb, pgm):
        for k in kits:
            if k['msb'] == msb and k['lsb'] == lsb and k['pgm'] == pgm:
                return k
        return None

    # MSB126 has no base kit -- see the module docstring.
    base = {127: find(127, 0, 1)}

    lines = []
    lines.extend(CPP_LINES)
    lines.append('// AUTO-GENERATED by tools/gen_drums.py - do not edit by hand.')
    lines.append('// Source: data/drums.json (XG Drum Map). Variation-kit inheritance')
    lines.append('// from Standard Kit is already resolved here, for the notes the PDF')
    lines.append('// shades "Same as Standard Kit" only. A note shaded "No sound" -- which')
    lines.append('// is EVERY blank in the MSB126 SFX kits -- is nullptr. Regenerate after edits.')
    lines.append('#pragma once')
    lines.append('#include <cstddef>')
    lines.append('namespace mu100 {')
    lines.append('')
    lines.append(f'static constexpr int kDrumFirstNote = {FIRST_NOTE};   // 0x0D')
    lines.append(f'static constexpr int kDrumLastNote  = {LAST_NOTE};   // 0x5B')
    lines.append(f'static constexpr int kDrumNoteSpan  = {LAST_NOTE - FIRST_NOTE + 1};')
    lines.append('')
    lines.append('struct DrumKit {')
    lines.append('    int         msb, lsb, pgm;   // pgm is 1-based (MIDI program = pgm-1)')
    lines.append('    const char* name;')
    lines.append('    // Drum-voice name per MIDI note kDrumFirstNote..kDrumLastNote')
    lines.append('    // (index = note - kDrumFirstNote); nullptr if no drum on that note.')
    lines.append('    const char* keys[kDrumNoteSpan];')
    lines.append('};')
    lines.append('')
    lines.append(f'static const DrumKit kDrumKits[] = {{')

    for k in kits:
        b = base.get(k['msb'])
        merged = {}
        if b is not None and b is not k:
            # only the notes the PDF shades "Same as Standard Kit"; a blank
            # shaded "No sound" stays silent even though the base has a voice.
            for n in k.get('inherits', []):
                if str(n) in b['keys']:
                    merged[str(n)] = b['keys'][str(n)]
        merged.update(k['keys'])   # this kit's own entries override the base

        cells = []
        for note in range(FIRST_NOTE, LAST_NOTE + 1):
            name = merged.get(str(note))
            cells.append(c_string(name) if name is not None else 'nullptr')

        lines.append(f'    {{{k["msb"]},{k["lsb"]},{k["pgm"]},{c_string(k["name"])},{{')
        # 8 cells per line for readability
        for i in range(0, len(cells), 8):
            lines.append('        ' + ','.join(cells[i:i + 8]) + ',')
        lines.append('    }},')

    lines.append('};')
    lines.append(f'static const int kDrumKitCount = {len(kits)};')
    lines.append('')
    lines.append('// Drum-voice name for (kit bank/program, note), or nullptr if the note')
    lines.append('// carries no drum or the kit is unknown. pgm is 1-based (= prg0 + 1).')
    lines.append('inline const char* drumVoiceName(int msb, int lsb, int pgm, int note)')
    lines.append('{')
    lines.append('    if (note < kDrumFirstNote || note > kDrumLastNote) return nullptr;')
    lines.append('    for (int i = 0; i < kDrumKitCount; ++i)')
    lines.append('    {')
    lines.append('        const DrumKit& k = kDrumKits[i];')
    lines.append('        if (k.msb == msb && k.lsb == lsb && k.pgm == pgm)')
    lines.append('            return k.keys[note - kDrumFirstNote];')
    lines.append('    }')
    lines.append('    return nullptr;')
    lines.append('}')
    lines.append('')
    lines.append('} // namespace mu100')
    lines.append('')

    out = os.path.join(HERE, 'codec', 'MU100Drums.h')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))

    # Quick validation summary.
    n_drum = sum(1 for k in kits if k['msb'] == 127)
    n_sfx  = sum(1 for k in kits if k['msb'] == 126)
    print(f'Wrote {out}')
    print(f'  {len(kits)} kits ({n_drum} drum MSB127 + {n_sfx} SFX MSB126)')
    std = find(127, 0, 1)
    print(f"  spot-check: Standard Kit note 60 (C3) = {std['keys'].get('60')!r}")


if __name__ == '__main__':
    main()
